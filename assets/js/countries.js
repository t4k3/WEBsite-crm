const COUNTRY_PLACEHOLDER = {
  it: "Seleziona il paese…",
  en: "Select your country…",
  fr: "Sélectionnez votre pays…",
};

// Popola il <select id="country"> nella lingua richiesta.
// Ordina alfabeticamente per lingua; il value resta il nome italiano.
function renderCountrySelect(lang) {
  const sel = document.getElementById("country");
  if (!sel) return;
  if (!["it", "en", "fr"].includes(lang)) lang = "it";

  const prev = sel.value; // preserva la selezione (value = nome IT)
  const list = WORLD_COUNTRIES.slice().sort((a, b) =>
    a[lang].localeCompare(b[lang], lang)
  );

  const ph = COUNTRY_PLACEHOLDER[lang] || COUNTRY_PLACEHOLDER.it;
  let html =
    `<option value="" disabled${prev ? "" : " selected"}>${ph}</option>`;
  html += list
    .map(
      (c) =>
        `<option value="${c.it}"${c.it === prev ? " selected" : ""}>${c[lang]}</option>`
    )
    .join("");
  sel.innerHTML = html;
}

window.renderCountrySelect = renderCountrySelect;
